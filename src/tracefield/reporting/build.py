"""Report building: Markdown and JSON with caveats attached to conclusions.

Every finding cites source locators, evidence IDs, digests, and collection
times. Caveats travel with the conclusions — exports must not strip them.
"""

from __future__ import annotations

import html
import json
from typing import Any

from tracefield.config import Settings
from tracefield.core.analysis import assess_claim
from tracefield.core.domain import Case
from tracefield.storage.database import Database
from tracefield.storage.repositories import (
    AssertionRepo,
    ClaimRepo,
    ClusterRepo,
    EventRepo,
    EvidenceRepo,
    RelationRepo,
    SourceRepo,
)

REPORT_SCHEMA_VERSION = 1


def build_case_payload(settings: Settings, db: Database, case: Case) -> dict[str, Any]:
    sources = SourceRepo(db).list_for_case(case.id)
    claims = ClaimRepo(db).list_for_case(case.id)
    evidence = EvidenceRepo(db).list_for_case(case.id)
    relations = RelationRepo(db).list_for_case(case.id)
    assertions = AssertionRepo(db).list_for_case(case.id)
    clusters = ClusterRepo(db).list_for_case(case.id)
    events = EventRepo(db).list_for_case(case.id)

    assessments = []
    for claim in claims:
        claim_rels = [r for r in relations if r.from_id == claim.id or r.to_id == claim.id]
        # Also treat relations where the claim is the subject via evidence links.
        v = assess_claim(claim, claim_rels, origin_clusters=len(clusters))
        assessments.append(v.model_dump())

    return {
        "report_schema_version": REPORT_SCHEMA_VERSION,
        "case": case.model_dump(),
        "counts": {
            "sources": len(sources),
            "claims": len(claims),
            "evidence": len(evidence),
            "relations": len(relations),
            "assertions": len(assertions),
            "origin_clusters": len(clusters),
            "analysis_events": len(events),
        },
        "sources": [s.model_dump() for s in sources],
        "claims": [c.model_dump() for c in claims],
        "evidence": [{**e.model_dump(), "storage_ref": e.storage_ref} for e in evidence],
        "relations": [r.model_dump() for r in relations],
        "assertions": [a.model_dump() for a in assertions],
        "origin_clusters": [c.model_dump() for c in clusters],
        "assessments": assessments,
        "global_caveats": [
            "SHA-256 digests prove byte-level integrity of stored objects, not "
            "truthfulness, authorship, or authenticity of content.",
            "Assessment labels are workflow states with documented criteria "
            "(rule versions recorded above), not probabilities of truth.",
            "Missing data is not evidence of absence. Origin clusters are "
            "hypotheses unless analyst-confirmed.",
            "This report was generated by an automated tool from local case "
            "data; analyst conclusions remain distinct from machine output.",
        ],
    }


def render_markdown(payload: dict[str, Any]) -> str:
    case = payload["case"]
    counts = payload["counts"]
    lines: list[str] = []
    lines.append(f"# Case Report — {case['title']}")
    lines.append("")
    lines.append(f"- **Case ID:** `{case['id']}`")
    lines.append(f"- **Status:** {case['status']}")
    lines.append(f"- **Purpose:** {case['purpose'] or '(none declared)'}")
    lines.append(f"- **Scope:** {case['scope'] or '(none declared)'}")
    lines.append(f"- **Created:** {case['created_at']}")
    lines.append(
        f"- **Records:** {counts['sources']} sources, {counts['claims']} claims, "
        f"{counts['evidence']} evidence, {counts['relations']} relations"
    )
    lines.append(f"- **Report schema:** v{payload['report_schema_version']}")
    lines.append("")

    lines.append("## Caveats")
    lines.append("")
    for c in payload["global_caveats"]:
        lines.append(f"> {c}")
        lines.append("")

    lines.append("## Sources")
    lines.append("")
    if not payload["sources"]:
        lines.append("_No sources recorded._")
    for s in payload["sources"]:
        lines.append(f"### `{s['id']}`")
        lines.append(f"- Locator: {s['locator']}")
        lines.append(f"- Type: {s['source_type']} via {s['access_method']}")
        lines.append(f"- First seen: {s['first_seen_at']}")
        if s["collected_at"]:
            lines.append(f"- Collected: {s['collected_at']}")
        if s["published_at"]:
            lines.append(f"- Published: {s['published_at']}")
        if s["limitations"]:
            lines.append(f"- Limitations: {s['limitations']}")
        lines.append("")

    lines.append("## Evidence")
    lines.append("")
    if not payload["evidence"]:
        lines.append("_No evidence attached._")
    for e in payload["evidence"]:
        lines.append(f"### `{e['id']}`")
        lines.append(f"- SHA-256: `{e['sha256']}`")
        lines.append(f"- Media type: {e['media_type']}")
        lines.append(f"- Size: {e['size_bytes']} bytes")
        lines.append(f"- Source: `{e['source_id']}`")
        lines.append(f"- Captured: {e['captured_at']}")
        lines.append(f"- Storage: `{e['storage_ref']}`")
        lines.append("")

    lines.append("## Claims and Assessments")
    lines.append("")
    if not payload["claims"]:
        lines.append("_No claims recorded._")
    assessments = {a["claim_id"]: a for a in payload["assessments"]}
    for c in payload["claims"]:
        lines.append(f"### `{c['id']}`")
        lines.append(f"> {c['text']}")
        lines.append("")
        lines.append(f"- Status: {c['status']} / review: {c['review_state']}")
        a = assessments.get(c["id"])
        if a:
            lines.append(f"- **Assessment:** `{a['outcome']}` (rules {a['rule_version']})")
            lines.append(
                f"- Supporting relations: {a['supporting_count']}; "
                f"contradicting: {a['contradicting_count']}"
            )
            lines.append(f"- Independence: {a['independence']}")
            for caveat in a["caveats"]:
                lines.append(f"- Caveat: {caveat}")
        lines.append("")

    if payload["relations"]:
        lines.append("## Relations")
        lines.append("")
        for r in payload["relations"]:
            lines.append(
                f"- `{r['id']}` {r['from_id']} —[{r['relation']}/{r['review_state']}]→ {r['to_id']}"
            )
            if r["rationale"]:
                lines.append(f"  - rationale: {r['rationale']}")
        lines.append("")

    if payload["origin_clusters"]:
        lines.append("## Origin Clusters (hypotheses)")
        lines.append("")
        for c in payload["origin_clusters"]:
            lines.append(f"### `{c['id']}` — {c['review_state']}")
            lines.append(f"- Members: {', '.join(c['member_ids'])}")
            lines.append(f"- Algorithm: {c['algorithm_version']}")
            for ind in c["indicators"]:
                lines.append(f"- Indicator: {ind}")
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "_Generated by TRACEFIELD. Assessment labels are workflow states, "
        "not guarantees of factual correctness._"
    )
    return "\n".join(lines) + "\n"


def _h(value: object) -> str:
    """HTML-escape any untrusted value for safe embedding."""
    return html.escape(str(value), quote=True)


def render_html(payload: dict[str, Any]) -> str:
    """Self-contained HTML report. No external resources, no JavaScript.

    Every string from case data is HTML-escaped — source text, claim text,
    and limitations are attacker-controllable in the general case, so a
    report opened in a browser must not execute injected markup. Locators
    are rendered as plain escaped text, never as hrefs, so ``javascript:``
    URLs cannot become clickable links.
    """
    case = payload["case"]
    counts = payload["counts"]
    assessments = {a["claim_id"]: a for a in payload["assessments"]}
    out: list[str] = []
    out.append("<!DOCTYPE html>")
    out.append('<html lang="en"><head><meta charset="utf-8">')
    out.append(f"<title>Case Report — {_h(case['title'])}</title>")
    out.append(
        "<style>"
        "body{font-family:system-ui,sans-serif;max-width:60rem;margin:2rem auto;"
        "padding:0 1rem;line-height:1.5;color:#111}"
        "code{background:#f2f2f2;padding:0 .25em}"
        "blockquote{border-left:3px solid #bbb;margin-left:0;padding-left:1em;color:#333}"
        ".caveat{background:#fff8e1;border:1px solid #e0c060;padding:.5em 1em;margin:.5em 0}"
        "h2{border-bottom:1px solid #ddd;padding-bottom:.2em}"
        ".footer{margin-top:3rem;font-size:.9em;color:#555;border-top:1px solid #ddd;padding-top:1em}"
        "</style></head><body>"
    )
    out.append(f"<h1>Case Report — {_h(case['title'])}</h1>")
    out.append("<ul>")
    out.append(f"<li><b>Case ID:</b> <code>{_h(case['id'])}</code></li>")
    out.append(f"<li><b>Status:</b> {_h(case['status'])}</li>")
    out.append(f"<li><b>Purpose:</b> {_h(case['purpose'] or '(none declared)')}</li>")
    out.append(f"<li><b>Scope:</b> {_h(case['scope'] or '(none declared)')}</li>")
    out.append(f"<li><b>Created:</b> {_h(case['created_at'])}</li>")
    out.append(
        f"<li><b>Records:</b> {counts['sources']} sources, {counts['claims']} claims, "
        f"{counts['evidence']} evidence, {counts['relations']} relations</li>"
    )
    out.append(f"<li><b>Report schema:</b> v{_h(payload['report_schema_version'])}</li>")
    out.append("</ul>")

    out.append("<h2>Caveats</h2>")
    for c in payload["global_caveats"]:
        out.append(f'<p class="caveat">{_h(c)}</p>')

    out.append("<h2>Sources</h2>")
    if not payload["sources"]:
        out.append("<p><i>No sources recorded.</i></p>")
    for s in payload["sources"]:
        out.append(f"<h3><code>{_h(s['id'])}</code></h3><ul>")
        out.append(f"<li>Locator: {_h(s['locator'])}</li>")
        out.append(f"<li>Type: {_h(s['source_type'])} via {_h(s['access_method'])}</li>")
        out.append(f"<li>First seen: {_h(s['first_seen_at'])}</li>")
        if s["collected_at"]:
            out.append(f"<li>Collected: {_h(s['collected_at'])}</li>")
        if s["published_at"]:
            out.append(f"<li>Published: {_h(s['published_at'])}</li>")
        if s["limitations"]:
            out.append(f"<li>Limitations: {_h(s['limitations'])}</li>")
        out.append("</ul>")

    out.append("<h2>Evidence</h2>")
    if not payload["evidence"]:
        out.append("<p><i>No evidence attached.</i></p>")
    for e in payload["evidence"]:
        out.append(f"<h3><code>{_h(e['id'])}</code></h3><ul>")
        out.append(f"<li>SHA-256: <code>{_h(e['sha256'])}</code></li>")
        out.append(f"<li>Media type: {_h(e['media_type'])}</li>")
        out.append(f"<li>Size: {_h(e['size_bytes'])} bytes</li>")
        out.append(f"<li>Source: <code>{_h(e['source_id'])}</code></li>")
        out.append(f"<li>Captured: {_h(e['captured_at'])}</li>")
        out.append(f"<li>Storage: <code>{_h(e['storage_ref'])}</code></li>")
        out.append("</ul>")

    out.append("<h2>Claims and Assessments</h2>")
    if not payload["claims"]:
        out.append("<p><i>No claims recorded.</i></p>")
    for c in payload["claims"]:
        out.append(f"<h3><code>{_h(c['id'])}</code></h3>")
        out.append(f"<blockquote>{_h(c['text'])}</blockquote>")
        out.append(f"<p>Status: {_h(c['status'])} / review: {_h(c['review_state'])}</p>")
        a = assessments.get(c["id"])
        if a:
            out.append(
                f"<p><b>Assessment:</b> <code>{_h(a['outcome'])}</code> "
                f"(rules {_h(a['rule_version'])})</p>"
            )
            out.append(
                f"<p>Supporting relations: {_h(a['supporting_count'])}; "
                f"contradicting: {_h(a['contradicting_count'])}</p>"
            )
            out.append(f"<p>Independence: {_h(a['independence'])}</p>")
            for caveat in a["caveats"]:
                out.append(f'<p class="caveat">Caveat: {_h(caveat)}</p>')

    if payload["relations"]:
        out.append("<h2>Relations</h2><ul>")
        for r in payload["relations"]:
            out.append(
                f"<li><code>{_h(r['id'])}</code> {_h(r['from_id'])} —"
                f"[{_h(r['relation'])}/{_h(r['review_state'])}]→ {_h(r['to_id'])}</li>"
            )
            if r["rationale"]:
                out.append(f"<ul><li>rationale: {_h(r['rationale'])}</li></ul>")
        out.append("</ul>")

    if payload["origin_clusters"]:
        out.append("<h2>Origin Clusters (hypotheses)</h2>")
        for c in payload["origin_clusters"]:
            out.append(f"<h3><code>{_h(c['id'])}</code> — {_h(c['review_state'])}</h3><ul>")
            out.append(f"<li>Members: {_h(', '.join(c['member_ids']))}</li>")
            out.append(f"<li>Algorithm: {_h(c['algorithm_version'])}</li>")
            for ind in c["indicators"]:
                out.append(f"<li>Indicator: {_h(ind)}</li>")
            out.append("</ul>")

    out.append(
        '<p class="footer">Generated by TRACEFIELD. Assessment labels are '
        "workflow states, not guarantees of factual correctness.</p>"
    )
    out.append("</body></html>")
    return "\n".join(out) + "\n"


def build_report(settings: Settings, db: Database, case: Case, *, fmt: str) -> str:
    payload = build_case_payload(settings, db, case)
    if fmt == "json":
        return json.dumps(payload, indent=2, sort_keys=True)
    if fmt == "markdown":
        return render_markdown(payload)
    if fmt == "html":
        return render_html(payload)
    raise ValueError(f"unsupported report format: {fmt} (use markdown, json, or html)")
